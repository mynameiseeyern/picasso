#!/usr/bin/env node
/**
 * Generates docs/components/ from the component folders.
 *
 * The README says component documentation deliberately does not live in docs/:
 * a doc in a separate folder drifts, a doc beside the code gets reviewed. That
 * is right, and it left the site with no Components section at all — 50
 * components reachable only as Storybook stories, so searching the site for a
 * component name found passing mentions and never the component.
 *
 * So these pages are generated rather than authored, on the same rule as
 * build-llms.mjs: every line comes from a file someone reads for another
 * reason — guidance.json, the component's own doc block, its props. Editing a
 * page here is pointless; the next build overwrites it. Change the component.
 */
import { readFileSync, writeFileSync, readdirSync, existsSync, mkdirSync, rmSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = join(ROOT, "packages/ui/src/components");
const OUT = join(ROOT, "docs/components");
const FIGMA = "https://www.figma.com/design";

/* A JSX comment, not an HTML one: these .md files are compiled as MDX, where
   raw HTML is refused outright ("Cannot handle unknown node `raw`"). */
const STAMP =
  "{/* Generated by scripts/build-component-docs.mjs — do not edit.\n" +
  "    The source is the component folder: guidance.json, the doc block and\n" +
  "    the props. Change those. */}\n";

/**
 * Everything on these pages is lifted from source comments, and MDX reads `<`
 * as the start of a JSX element and `{` as the start of an expression. A doc
 * block mentioning `<input>` or `{type.family.sans}` therefore breaks the
 * build — so prose is escaped on the way out. Code fences are emitted
 * separately and are left alone.
 */
const mdx = (s) => String(s).replace(/</g, "&lt;").replace(/\{/g, "&#123;");

/* ── reading a component folder ───────────────────────────────────────── */

const titleCase = (slug) =>
  slug.replace(/-/g, " ").replace(/^./, (c) => c.toUpperCase());

/** Every ⚠️ paragraph in the doc block: the things that bite. */
function warnings(src) {
  const block = src.match(/\/\*\*\n([\s\S]*?)\n \*\//);
  if (!block) return [];
  const text = block[1]
    .split("\n")
    .map((l) => l.replace(/^ \* ?/, "").replace(/^ \*$/, ""))
    .join("\n");
  return [...text.matchAll(/⚠️\s*([\s\S]*?)(?=\n\s*\n|\n⚠️|$)/g)]
    .map((m) => m[1].replace(/\s*\n\s*/g, " ").trim())
    .filter(Boolean);
}

/**
 * Props, from the exported `<Name>Props` interface. Each member in this
 * library carries its own doc comment, which is the description — so nothing
 * here is written, only lifted.
 */
function props(src) {
  // Every exported Props interface, not just the first: a compound component
  // keeps its API in the sub-components (DialogContentProps, ToastProps …),
  // and reading only the first left a dozen components looking propless.
  const groups = [];
  for (const iface of src.matchAll(/export interface (\w*Props)[\s\S]*?\{\n([\s\S]*?)\n\}/g)) {
    const out = [];
    const re = /\/\*\*([\s\S]*?)\*\/\s*\n\s*(\w+)(\??):\s*([\s\S]*?);\n/g;
    let m;
    while ((m = re.exec(iface[2] + "\n")) !== null) {
      const doc = m[1]
        .split("\n")
        .map((l) => l.replace(/^\s*\*?\s?/, ""))
        .join(" ")
        .replace(/\s+/g, " ")
        .trim();
      // A union written across several lines reads fine on one.
      out.push({ name: m[2], optional: m[3] === "?", type: m[4].replace(/\s+/g, " ").trim(), doc });
    }
    if (out.length) groups.push({ name: iface[1], members: out });
  }
  return groups;
}

const esc = (s) => mdx(s).replace(/\|/g, "\\|");

/**
 * The cva variants. For a component whose own props interface is empty — it
 * takes the element's props and nothing else — the variant axes ARE the API,
 * and they were going undocumented.
 */
function variants(src) {
  const out = [];
  for (const block of src.matchAll(/cva\(([\s\S]*?)\n\);/g)) {
    const body = block[1];
    const v = body.match(/variants:\s*\{([\s\S]*?)\n\s{4}\}/);
    if (!v) continue;
    const defaults = {};
    const d = body.match(/defaultVariants:\s*\{([^}]*)\}/);
    if (d) for (const m of d[1].matchAll(/(\w+):\s*"([^"]+)"/g)) defaults[m[1]] = m[2];
    // Each axis is `name: { option: "classes", ... }` at one indent level.
    for (const axis of v[1].matchAll(/^\s{6}(\w+):\s*\{([\s\S]*?)^\s{6}\}/gm)) {
      const options = [...axis[2].matchAll(/^\s{8}"?([\w-]+)"?:/gm)].map((m) => m[1]);
      if (options.length) out.push({ name: axis[1], options, default: defaults[axis[1]] });
    }
  }
  return out;
}

/* ── the page ─────────────────────────────────────────────────────────── */

function page(c) {
  const L = [];
  L.push("---");
  L.push(`title: ${c.title}`);
  L.push(`description: ${JSON.stringify(c.guidance.summary.replace(/\n/g, " "))}`);
  L.push("---");
  L.push("");
  L.push(STAMP);
  L.push(`# ${c.title}`);
  L.push("");
  L.push(mdx(c.guidance.summary));
  L.push("");

  L.push("## Import");
  L.push("");
  L.push("```tsx");
  L.push(`import { ${c.exports.join(", ")} } from "@ir/ui";`);
  L.push("```");
  L.push("");

  if (c.warnings.length) {
    L.push("## Watch out");
    L.push("");
    for (const w of c.warnings) L.push(`- ${mdx(w)}`);
    L.push("");
  }

  if (c.variants.length) {
    L.push("## Variants");
    L.push("");
    L.push("| Axis | Options | Default |");
    L.push("|---|---|---|");
    for (const v of c.variants)
      L.push(`| \`${v.name}\` | ${v.options.map((o) => `\`${o}\``).join(" · ")} | ${v.default ? `\`${v.default}\`` : "—"} |`);
    L.push("");
  }

  if (c.props.length) {
    L.push("## Props");
    L.push("");
    for (const g of c.props) {
      // One table per interface when a component has several; no heading when
      // there is only one, because the section heading already says Props.
      if (c.props.length > 1) {
        L.push(`### ${g.name.replace(/Props$/, "")}`);
        L.push("");
      }
      L.push("| Prop | Type | Required | What it does |");
      L.push("|---|---|---|---|");
      for (const p of g.members)
        L.push(`| \`${p.name}\` | \`${esc(p.type)}\` | ${p.optional ? "" : "yes"} | ${esc(p.doc)} |`);
      L.push("");
    }
  }

  if (!c.props.length && !c.variants.length) {
    L.push("## Props");
    L.push("");
    L.push(
      "Takes the props of the element it renders, and nothing of its own — " +
        "styling is the component's business, not the caller's.",
    );
    L.push("");
  }

  const pairs = c.guidance.pairs ?? [];
  if (pairs.length) {
    L.push("## Do and don't");
    L.push("");
    for (const p of pairs) {
      L.push(`### ${mdx(p.do)}`);
      L.push("");
      L.push(`**Don't** — ${mdx(p.dont)}`);
      L.push("");
      L.push(mdx(p.why));
      L.push("");
    }
  }

  if (c.guidance.a11y?.length) {
    L.push("## Accessibility");
    L.push("");
    for (const a of c.guidance.a11y) L.push(`- ${mdx(a)}`);
    L.push("");
  }

  L.push("## Where it is drawn");
  L.push("");
  const fig = c.guidance.figma;
  if (fig && typeof fig === "object" && fig.nodeId) {
    L.push(
      `[Figma](${FIGMA}/${fig.fileKey}/?node-id=${String(fig.nodeId).replace(":", "-")}) — ` +
        `structure from ${c.guidance.structureFrom ?? "the file"}, measurements from ${c.guidance.measurementsFrom ?? "the file"}.`,
    );
  } else if (fig && typeof fig === "object") {
    L.push(mdx(fig.note ?? "Not drawn in Figma."));
  } else {
    L.push(typeof fig === "string" ? mdx(fig) : "Not recorded.");
  }
  L.push("");
  L.push(`[Open in Storybook](/components/?path=/docs/components-${c.slug}--docs)`);
  L.push("");
  return L.join("\n");
}

function indexPage(all) {
  const L = [];
  L.push("---");
  L.push("title: Components");
  L.push(
    "description: Every component in Picasso, what it is for, and whether it is drawn, built and guided. This is the status page as well as the index.",
  );
  L.push("---");
  L.push("");
  L.push(STAMP);
  L.push("# Components");
  L.push("");
  L.push(
    `${all.length} components. Each page is generated from the component's own folder — its \`guidance.json\`, ` +
      "its doc block and its props — so a change to the code and a change to this page land in the same commit.",
  );
  L.push("");
  const drawn = all.filter((c) => c.guidance.figma?.nodeId).length;
  const guided = all.filter((c) => (c.guidance.pairs ?? []).length).length;
  L.push(
    `**${drawn} of ${all.length}** are drawn in Figma; the rest were built in code first. ` +
      `**${guided}** carry Do-and-Don't guidance.`,
  );
  L.push("");
  L.push("| Component | What it is for | In Figma | Guidance |");
  L.push("|---|---|---|---|");
  for (const c of all) {
    const fig = c.guidance.figma;
    const inFigma = fig && typeof fig === "object" && fig.nodeId ? "yes" : fig && typeof fig === "string" ? "yes" : "code first";
    L.push(
      `| [${c.title}](/docs/components/${c.slug}) | ${esc(c.guidance.summary)} | ${inFigma} | ${(c.guidance.pairs ?? []).length || "—"} |`,
    );
  }
  L.push("");
  return L.join("\n");
}

/* ── run ──────────────────────────────────────────────────────────────── */

const all = [];
for (const slug of readdirSync(SRC).sort()) {
  const dir = join(SRC, slug);
  const g = join(dir, "guidance.json");
  if (!existsSync(g)) continue;
  const guidance = JSON.parse(readFileSync(g, "utf8"));

  // The component file is the one named after the folder.
  const file = join(dir, `${slug}.tsx`);
  const src = existsSync(file) ? readFileSync(file, "utf8") : "";
  const exports = [
    ...[...src.matchAll(/^export function (\w+)/gm)].map((m) => m[1]),
    ...[...src.matchAll(/^export const (\w+) = React\.forwardRef/gm)].map((m) => m[1]),
  ];

  all.push({
    slug,
    title: titleCase(slug),
    guidance,
    warnings: warnings(src),
    props: props(src),
    variants: variants(src),
    exports: exports.length ? exports : [guidance.component ?? titleCase(slug)],
  });
}

rmSync(OUT, { recursive: true, force: true });
mkdirSync(OUT, { recursive: true });
writeFileSync(join(OUT, "index.md"), indexPage(all));
for (const c of all) writeFileSync(join(OUT, `${c.slug}.md`), page(c));
writeFileSync(
  join(OUT, "meta.json"),
  JSON.stringify({ title: "Components", pages: ["index", ...all.map((c) => c.slug)] }, null, 2) + "\n",
);

console.log(`docs/components: ${all.length} pages`);
const bare = all.filter((c) => !c.props.length && !c.variants.length).map((c) => c.slug);
if (bare.length) console.log(`  no own props and no variants: ${bare.join(", ")}`);
