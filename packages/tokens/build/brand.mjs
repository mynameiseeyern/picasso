#!/usr/bin/env node
/**
 * Generate a brand's ramps and its resolved on-colours.
 *
 *   node build/brand.mjs prognosis --brand "#6D248B" --accent "#0E9488"
 *
 * Prints a themes.css block: the two ramps, plus the fg/on/* overrides that
 * the measured contrast demands. Nothing here is decided by eye.
 */
import { buildRamp, inkFor, contrast, hexToRgb, STEPS } from "./ramp.mjs";

const argv = process.argv.slice(2);
const name = argv[0];
const arg = (k, d) => { const i = argv.indexOf(`--${k}`); return i < 0 ? d : argv[i + 1]; };
if (!name || !arg("brand")) {
  console.error('usage: node build/brand.mjs <name> --brand "#RRGGBB" [--accent "#RRGGBB"] [--neutral cool|warm]');
  process.exit(1);
}

const ramps = { brand: buildRamp(arg("brand")) };
if (arg("accent")) ramps.accent = buildRamp(arg("accent"));

/* Which step each semantic surface uses, per mode. These mirror light.json /
 * dark.json — if those change, change these. */
const SURFACES = {
  light: { emphasis: 600, subtle: 50, "subtle-ink": 800 },
  dark: { emphasis: 500, subtle: 950, "subtle-ink": 200 },
};
const DARK_INK = { light: "#161618", dark: "#161618" };

const lines = [];
lines.push(`/* ${name} — generated by build/brand.mjs. Do not hand-edit. */`);
lines.push(`[data-brand="${name}"] {`);
for (const [family, ramp] of Object.entries(ramps)) {
  for (const s of STEPS) lines.push(`  --palette-${family}-${s}: ${ramp[s]};`);
  lines.push("");
}
lines.pop();
lines.push("}");

const report = [];
for (const mode of ["light", "dark"]) {
  const sel = mode === "light" ? `[data-brand="${name}"]` : `.dark [data-brand="${name}"], [data-brand="${name}"].dark`;
  const overrides = [];
  for (const [family, ramp] of Object.entries(ramps)) {
    const token = family === "brand" ? "primary" : "accent";
    const bg = ramp[SURFACES[mode].emphasis];
    const { ink, onWhite, onDark } = inkFor(bg, { dark: DARK_INK[mode] });
    const value = ink === "light" ? "var(--palette-white)" : "var(--palette-neutral-950)";
    overrides.push(`  --fg-on-${token}-emphasis: ${value};`);
    report.push({
      mode, token: `fg/on/${token}-emphasis`, surface: bg,
      ink, white: onWhite, dark: onDark,
      chose: ink === "light" ? "white" : "neutral-950",
    });
  }
  if (overrides.length) {
    lines.push("");
    lines.push(`${sel} {`);
    lines.push(...overrides);
    lines.push("}");
  }
}

console.log(lines.join("\n"));
console.error("\n/* contrast, measured — not chosen */");
console.error(report.map(r =>
  `   ${r.mode.padEnd(6)} ${r.token.padEnd(26)} on ${r.surface}  white ${String(r.white).padStart(5)}  dark ${String(r.dark).padStart(5)}  →  ${r.chose}`
).join("\n"));
